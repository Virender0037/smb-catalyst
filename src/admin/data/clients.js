export const clientById = (id) => mockClients.find((c) => c.id === id) ?? null;

/** Short label used across tables, drawers and the activity feed. */
export const clientLabel = (id) => clientById(id)?.practice.name ?? '—';

/** Engagement-stage roll-up for the dashboard. */
export function engagementsByStage(clients = mockClients) {
  return engagementStages
    .map((stage) => ({ stage, count: clients.filter((c) => c.crmStage === stage).length }))
    .filter((row) => row.count > 0);
}
